static const uint8_t SPI_ZERO[24] = { 0 };

const spi_entry_t SPI_TABLE[] = {
    { 0x6010, 16, SPI_6010 },
    { 0x6000, 16, SPI_6000 },
    { 0x6050, 13, spi_color_6050 },
    { 0x6080, 24, SPI_6080 },
    { 0x6098, 18, SPI_6098 },
    { 0x603D, 25, SPI_603D },
    { 0x6020, 24, SPI_ZERO },
    { 0x8010, 24, SPI_FF   },
    { 0x8028, 24, SPI_FF   },
};

uint8_t const SPI_TABLE_N =
    (uint8_t)(sizeof(SPI_TABLE) / sizeof(SPI_TABLE[0]));

const spi_entry_t *spi_find(uint16_t addr)
{
    uint8_t k;
    for (k = 0u; k < SPI_TABLE_N; k++) {
        if (SPI_TABLE[k].addr == addr) {
            return &SPI_TABLE[k];
        }
    }
    return NULL;
}
